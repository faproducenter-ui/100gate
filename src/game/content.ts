export type PuzzleKind = "search" | "power" | "safe";

export interface ChapterDef {
  id: number;
  title: string;
  location: string;
  subtitle: string;
  story: string;
  palette: { wall: string; wood: string; fog: string; accent: string; light: string };
  propStyle: "manor" | "medical" | "school" | "hotel" | "bunker" | "orphanage" | "archive" | "theatre" | "laboratory" | "void";
  lore: string[];
}

export interface StoryDocument {
  id: string;
  title: string;
  body: string;
  clue?: string;
}

export interface LevelDef {
  index: number;
  chapter: ChapterDef;
  roomNumber: number;
  roomName: string;
  seed: number;
  puzzle: PuzzleKind;
  keyContainer: number;
  fuseContainer: number;
  code: string;
  documents: StoryDocument[];
  enemy: boolean;
}

