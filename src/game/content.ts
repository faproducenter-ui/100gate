export function hashSeed(value: number): number {
  let t = value + 0x6d2b79f5;
  t = Math.imul(t ^ (t >>> 15), t | 1);
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
  return (t ^ (t >>> 14)) >>> 0;
}

export function randomFrom(seed: number): () => number {
  let a = hashSeed(seed);
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function getLevel(index: number): LevelDef {
  const safeIndex = Math.max(0, Math.min(99, Math.floor(index)));
  const chapterIndex = Math.floor(safeIndex / 10);
  const roomNumber = safeIndex % 10;
  const chapter = CHAPTERS[chapterIndex];
  const seed = hashSeed(9001 + safeIndex * 7919);
  const rand = randomFrom(seed);
  const keyContainer = Math.floor(rand() * CONTAINER_NAMES.length);
  let fuseContainer = Math.floor(rand() * CONTAINER_NAMES.length);
  if (fuseContainer === keyContainer) fuseContainer = (fuseContainer + 2) % CONTAINER_NAMES.length;
  const puzzle: PuzzleKind = roomNumber === 0 ? "search" : (["search", "search", "power", "search", "safe"] as PuzzleKind[])[(roomNumber + chapterIndex) % 5];
  const code = String(1000 + Math.floor(rand() * 9000));
  const roomName = ROOM_NAMES[chapterIndex][roomNumber];
  const clue = puzzle === "power"
    ? `Сначала найдите предохранитель: он в ${CONTAINER_NAMES[fuseContainer]}. После восстановления питания осмотрите ${CONTAINER_NAMES[keyContainer]}.`
    : puzzle === "safe"
      ? `За портретом находится сейф. Четырёхзначный код: ${code}. Внутри — ключ от выхода.`
      : `Ключ спрятан в ${CONTAINER_NAMES[keyContainer]}. Остальные ящики могут выдать ваши действия шумом.`;
  const title = roomNumber === 0 ? `Вводная записка · ${roomName}` : `Улика ${chapterIndex + 1}.${roomNumber + 1}`;
  const intro = roomNumber === 0 ? `${chapter.story}\n\n` : "";
  const documents: StoryDocument[] = [
    {
      id: `case-${safeIndex}-clue`,
      title,
      body: `${intro}Запись обнаружена в локации «${roomName}». ${chapter.lore[roomNumber % chapter.lore.length]}\n\nНаблюдение: предметы здесь реагируют на последовательность действий. Не оставляйте найденные улики без внимания.`,
      clue,
    },
    {
      id: `case-${safeIndex}-lore`,
      title: `Материалы дела · ${chapter.title}`,
      body: `${chapter.lore[(roomNumber + 1) % chapter.lore.length]}\n\nФрагмент ${roomNumber + 1} из 10. ${chapter.subtitle}\n\nНа полях документа неразборчиво написано: «Смотритель слышит спешку. Свет помогает искать, но помогает и ему».`,
    },
  ];
  return {
    index: safeIndex,
    chapter,
    roomNumber,
    roomName,
    seed,
    puzzle,
    keyContainer,
    fuseContainer,
    code,
    documents,
    enemy: roomNumber >= 2 || chapterIndex > 0,
  };
}

