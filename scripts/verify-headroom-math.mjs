import assert from 'node:assert/strict';
import * as T from 'three';
import {Headroom} from '../src/episode/headroom.ts';
const mat=new T.MeshBasicMaterial();
const slab=new T.Mesh(new T.BoxGeometry(2,.2,2),mat);slab.position.y=3.5;
const flat=new Headroom([slab]);
assert(Math.abs(flat.heightAt(0,0,0)-3.4)<1e-7);
assert.equal(flat.heightAt(0,0,3.6),Infinity,'the floor under the feet is not a ceiling');
assert.equal(flat.heightAt(1.1,0,0,0),Infinity);
assert(Math.abs(flat.heightAt(1.1,0,0,.22)-3.4)<1e-7,'capsule edge clearance must count');
slab.geometry.translate(50,0,0);slab.removeFromParent();slab.geometry.dispose();
assert(Math.abs(flat.heightAt(0,0,0)-3.4)<1e-7,'static batching/disposal must not alter the collision snapshot');
const roof=new T.Mesh(new T.BoxGeometry(10,.2,4),mat);roof.position.y=5;roof.rotation.z=.4;
const slope=new Headroom([roof]);
assert(Math.abs(slope.heightAt(2,0,0,0)-(5+2*Math.tan(.4)-.1/Math.cos(.4)))<1e-7);
const parent=new T.Group();parent.position.set(3,0,-10);parent.rotation.y=Math.PI/2;
const lintel=new T.Mesh(new T.BoxGeometry(1.6,.2,.2),mat);lintel.position.y=2.5;parent.add(lintel);
assert(Math.abs(new Headroom([lintel]).heightAt(3,-10,0,0)-2.4)<1e-7);
roof.geometry.dispose();lintel.geometry.dispose();mat.dispose();
console.log('PASS real solid headroom: flat slab, capsule edge, sloped roof, rotated parent and independent batch snapshots');
